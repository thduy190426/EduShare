CREATE TABLE IF NOT EXISTS LICH_SU_XU (
    MaGD INT AUTO_INCREMENT PRIMARY KEY,
    MaND INT NOT NULL,
    LoaiGiaoDich ENUM('NapXu', 'MuaTaiLieu', 'BanTaiLieu', 'TruXuAdmin', 'ThuongXu', 'HoanXu', 'PhatXu') NOT NULL,
    SoXuThayDoi INT NOT NULL,
    MoTa TEXT,
    NgayGiaoDich DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (MaND) REFERENCES NGUOIDUNG(MaND)
);

CREATE TABLE IF NOT EXISTS YEU_CAU_GIAO_VIEN (
    MaYeuCau INT AUTO_INCREMENT PRIMARY KEY,
    MaND INT NOT NULL,
    MinhChungURL VARCHAR(255) NOT NULL,
    TrangThai ENUM('ChoDuyet', 'DaDuyet', 'TuChoi') DEFAULT 'ChoDuyet',
    LyDoTuChoi TEXT DEFAULT NULL,
    NgayTao DATETIME DEFAULT CURRENT_TIMESTAMP,
    NgayCapNhat DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (MaND) REFERENCES NGUOIDUNG(MaND)
);

CREATE TABLE IF NOT EXISTS PROMO_CODE (
    MaPromo INT AUTO_INCREMENT PRIMARY KEY,
    Code VARCHAR(50) NOT NULL UNIQUE,
    DiscountPercent INT NOT NULL,
    Description TEXT,
    IsActive BOOLEAN DEFAULT TRUE,
    NgayTao DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS REFRESH_TOKENS (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    MaND INT NOT NULL,
    Token VARCHAR(500) NOT NULL,
    ExpiresAt DATETIME NOT NULL,
    CreatedAt DATETIME DEFAULT CURRENT_TIMESTAMP,
    Revoked BOOLEAN DEFAULT FALSE,
    FOREIGN KEY (MaND) REFERENCES NGUOIDUNG(MaND) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS CAIDAT_CHAT (
    MaND INT NOT NULL,
    MaND_DoiTac INT NOT NULL,
    DaGhim BOOLEAN DEFAULT FALSE,
    DaChan BOOLEAN DEFAULT FALSE,
    NgayXoa DATETIME DEFAULT NULL,
    PRIMARY KEY (MaND, MaND_DoiTac),
    FOREIGN KEY (MaND) REFERENCES NGUOIDUNG(MaND) ON DELETE CASCADE,
    FOREIGN KEY (MaND_DoiTac) REFERENCES NGUOIDUNG(MaND) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS TINNHAN (
    MaTN INT AUTO_INCREMENT PRIMARY KEY,
    NguoiGui INT NOT NULL,
    NguoiNhan INT NOT NULL,
    NoiDung TEXT NOT NULL,
    DaDoc BOOLEAN DEFAULT FALSE,
    NgayGui DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (NguoiGui) REFERENCES NGUOIDUNG(MaND) ON DELETE CASCADE,
    FOREIGN KEY (NguoiNhan) REFERENCES NGUOIDUNG(MaND) ON DELETE CASCADE
);
CREATE INDEX idx_tinnhan_gui_nhan ON TINNHAN(NguoiGui, NguoiNhan);

CREATE INDEX idx_tailieu_trangthai ON TAILIEU(TrangThaiKiemDuyet);

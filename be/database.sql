CREATE TABLE IF NOT EXISTS TRUONGHOC (
    MaTruong INT AUTO_INCREMENT PRIMARY KEY,
    TenTruong VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS KHOANGANH (
    MaKhoa INT AUTO_INCREMENT PRIMARY KEY,
    TenKhoa VARCHAR(255) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS RESET_PASSWORD_OTP (
    Email VARCHAR(255) PRIMARY KEY,
    OTP VARCHAR(10) NOT NULL,
    ExpiresAt DATETIME NOT NULL
);

CREATE TABLE IF NOT EXISTS DELETE_ACCOUNT_OTP (
    Email VARCHAR(255) PRIMARY KEY,

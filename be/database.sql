CREATE INDEX idx_baocaovipham_trangthai ON BAOCAOVIPHAM(TrangThai);
CREATE INDEX idx_baocaovipham_ngaybaocao ON BAOCAOVIPHAM(NgayBaoCao);

CREATE INDEX idx_giaodich_napxu_trangthai ON GIAODICH_NAPXU(TrangThai);
CREATE INDEX idx_giaodich_napxu_ngaytao ON GIAODICH_NAPXU(NgayTao);

CREATE INDEX idx_nhom_ngaytao ON NHOM(NgayTao);
CREATE TABLE IF NOT EXISTS TINNHAN_NHOM (
    MaTN INT AUTO_INCREMENT PRIMARY KEY,
    MaNhom INT NOT NULL,
    MaND_Gui INT NOT NULL,
    NoiDung TEXT NOT NULL,
    LoaiTinNhan ENUM('text', 'image', 'file') DEFAULT 'text',
    TraLoiCho_MaTN INT DEFAULT NULL,
    DaThuHoi BOOLEAN DEFAULT FALSE,
    DaChinhSua BOOLEAN DEFAULT FALSE,
    Reactions JSON DEFAULT NULL,
    NgayGui DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (MaNhom) REFERENCES NHOM(MaNhom) ON DELETE CASCADE,
    FOREIGN KEY (MaND_Gui) REFERENCES NGUOIDUNG(MaND) ON DELETE CASCADE,
    FOREIGN KEY (TraLoiCho_MaTN) REFERENCES TINNHAN_NHOM(MaTN) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS TINNHAN_NHOM_DA_XOA (
    MaTN INT NOT NULL,
    MaND INT NOT NULL,
    PRIMARY KEY (MaTN, MaND),
    FOREIGN KEY (MaTN) REFERENCES TINNHAN_NHOM(MaTN) ON DELETE CASCADE,
    FOREIGN KEY (MaND) REFERENCES NGUOIDUNG(MaND) ON DELETE CASCADE
);
